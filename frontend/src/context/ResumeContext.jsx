import React, { createContext, useContext, useState, useEffect, useCallback } from 'react';
import { sampleResumes } from '../mock/mockResumes';
import { mockAnalysisResults } from '../mock/mockAnalysisData';
import { mockAtsResults } from '../mock/mockAtsData';
import { mockJobMatchResults } from '../mock/mockJobMatchData';
import { initialResumeHistory } from '../mock/mockHistoryData';
import { resumeService } from '../services/resumeService';
import { historyService } from '../services/historyService';
import { analysisService } from '../services/analysisService';
import { atsService } from '../services/atsService';
import { jobMatchService } from '../services/jobMatchService';

const ResumeContext = createContext(null);

export function ResumeProvider({ children }) {
  // Currently inspected resume
  const [currentResumeId, setCurrentResumeId] = useState('res_001');
  const [resumeList, setResumeList] = useState(sampleResumes);
  const [history, setHistory] = useState(initialResumeHistory);

  // Analysis states
  const [activeAnalysis, setActiveAnalysis] = useState(mockAnalysisResults.res_001);
  const [activeAts, setActiveAts] = useState(mockAtsResults.res_001);
  const [activeJobMatch, setActiveJobMatch] = useState(mockJobMatchResults.res_001);

  // Initial load from backend
  useEffect(() => {
    historyService.getResumeHistory().then(res => {
      if (res && res.length > 0) {
        setHistory(res);
        setResumeList(res);
      }
    }).catch(() => {});
  }, []);

  // Upload & Analysis Progress States
  const [uploadStatus, setUploadStatus] = useState({
    isUploading: false,
    progress: 0,
    stage: '',
    error: null,
    isSuccess: false
  });

  // Switch inspected resume
  const selectResume = useCallback(async (id) => {
    setCurrentResumeId(id);

    try {
      const [analysis, ats, jobMatch] = await Promise.all([
        analysisService.getResumeAnalysis(id),
        atsService.getAtsAnalysis(id),
        jobMatchService.getJobMatchAnalysis(id)
      ]);

      if (analysis) setActiveAnalysis(analysis);
      else setActiveAnalysis(mockAnalysisResults[id] || mockAnalysisResults.res_001);

      if (ats) setActiveAts(ats);
      else setActiveAts(mockAtsResults[id] || mockAtsResults.res_001);

      if (jobMatch) setActiveJobMatch(jobMatch);
      else setActiveJobMatch(mockJobMatchResults[id] || mockJobMatchResults.res_001);
    } catch {
      setActiveAnalysis(mockAnalysisResults[id] || mockAnalysisResults.res_001);
      setActiveAts(mockAtsResults[id] || mockAtsResults.res_001);
      setActiveJobMatch(mockJobMatchResults[id] || mockJobMatchResults.res_001);
    }
  }, []);

  // Upload & Analyze workflow
  const uploadAndAnalyze = async (file, jobDescription = null) => {
    setUploadStatus({
      isUploading: true,
      progress: 10,
      stage: 'Uploading resume document...',
      error: null,
      isSuccess: false
    });

    try {
      // Step 1: Upload simulation
      const uploaded = await resumeService.uploadResume(file, jobDescription, (pct) => {
        setUploadStatus(prev => ({
          ...prev,
          progress: Math.min(60, pct),
          stage: pct < 50 ? 'Extracting text and structural metadata...' : 'Validating formatting & layout hierarchy...'
        }));
      });

      // Step 2: AI & ATS Analysis simulation
      setUploadStatus(prev => ({
        ...prev,
        progress: 75,
        stage: 'Running ATS compatibility scan & keyword matching...'
      }));

      await new Promise(r => setTimeout(r, 600));

      if (jobDescription && jobDescription.text) {
        setUploadStatus(prev => ({
          ...prev,
          progress: 90,
          stage: 'Evaluating semantic alignment with target Job Description...'
        }));
        await new Promise(r => setTimeout(r, 500));
      }

      setUploadStatus({
        isUploading: false,
        progress: 100,
        stage: 'Analysis completed successfully!',
        error: null,
        isSuccess: true
      });

      // Add to local state and history
      const newResumeRecord = {
        ...uploaded,
        id: uploaded.id,
        date: 'Just now',
        rawDate: new Date().toISOString()
      };

      setResumeList(prev => [newResumeRecord, ...prev]);
      setHistory(prev => [newResumeRecord, ...prev]);

      // Set active
      setCurrentResumeId(newResumeRecord.id);
      
      // Fetch live analysis data generated by backend for this specific resume
      try {
        const [analysis, ats, jobMatch] = await Promise.all([
          analysisService.getResumeAnalysis(newResumeRecord.id),
          atsService.getAtsAnalysis(newResumeRecord.id),
          jobMatchService.getJobMatchAnalysis(newResumeRecord.id)
        ]);
        if (analysis) setActiveAnalysis(analysis);
        if (ats) setActiveAts(ats);
        if (jobMatch) setActiveJobMatch(jobMatch);
      } catch {
        const customizedAnalysis = {
          ...mockAnalysisResults.res_001,
          id: 'anl_' + newResumeRecord.id,
          resumeId: newResumeRecord.id,
          fileName: newResumeRecord.fileName,
          targetJobTitle: jobDescription?.title || 'Software Engineer',
          targetCompany: jobDescription?.company || 'Target Employer'
        };
        setActiveAnalysis(customizedAnalysis);
      }

      return newResumeRecord;
    } catch (err) {
      setUploadStatus({
        isUploading: false,
        progress: 0,
        stage: '',
        error: err.message || 'Failed to process resume. Please try again.',
        isSuccess: false
      });
      throw err;
    }
  };

  // History operations
  const renameHistoryItem = async (id, newName) => {
    await historyService.renameResume(id, newName);
    setHistory(prev => prev.map(item => item.id === id ? { ...item, fileName: newName } : item));
    setResumeList(prev => prev.map(item => item.id === id ? { ...item, fileName: newName } : item));
  };

  const deleteHistoryItem = async (id) => {
    await historyService.deleteResumeHistory(id);
    setHistory(prev => prev.filter(item => item.id !== id));
    setResumeList(prev => prev.filter(item => item.id !== id));
    if (currentResumeId === id) {
      const remaining = history.filter(item => item.id !== id);
      if (remaining.length > 0) {
        selectResume(remaining[0].id);
      }
    }
  };

  const resetUploadState = () => {
    setUploadStatus({
      isUploading: false,
      progress: 0,
      stage: '',
      error: null,
      isSuccess: false
    });
  };

  const currentResume = resumeList.find(r => r.id === currentResumeId) || resumeList[0] || sampleResumes[0];

  return (
    <ResumeContext.Provider
      value={{
        currentResumeId,
        currentResume,
        resumeList,
        history,
        activeAnalysis,
        activeAts,
        activeJobMatch,
        uploadStatus,
        selectResume,
        uploadAndAnalyze,
        renameHistoryItem,
        deleteHistoryItem,
        resetUploadState
      }}
    >
      {children}
    </ResumeContext.Provider>
  );
}

export const useResume = () => {
  const context = useContext(ResumeContext);
  if (!context) {
    throw new Error('useResume must be used within a ResumeProvider');
  }
  return context;
};
